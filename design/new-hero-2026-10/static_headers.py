#!/usr/bin/env python3
"""
The security headers for the static folders (card #6449).

people/, experts/, community/ (and the team/ redirect stubs) are real folders on the server, so
Apache serves their index.html itself and WordPress, which sends the security headers
(wp/inc/security.php), never sees the request. Each folder gets an .htaccess that sets the same
headers, with the same values: both read wp/inc/security-headers.json.

    people/build-profiles.py   writes people/.htaccess (with the /people/ 301), experts/.htaccess
                               and community/.htaccess
    deploy-wp-theme-vimexx.py  uploads them with the pages, and team/.htaccess from block() below

"Header always set" covers every status (the 301 of /people/ too); Strict-Transport-Security only
over HTTPS (expr=%{HTTPS} == 'on'), as WordPress only sends it when is_ssl(). Inside <IfModule mod_headers.c>,
so a server without the module still serves the pages. Needs AllowOverride FileInfo, which
WordPress' own .htaccess rules already rely on.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = os.path.join(HERE, "wp", "inc", "security-headers.json")


def _spec():
    with open(SPEC, encoding="utf-8") as f:
        return json.load(f)


def headers(is_ssl=True):
    """header name -> value, as prospergenics_2026_security_headers() in inc/security.php builds it."""
    spec = _spec()
    out = {}
    for name, value in list(spec["headers"].items()) + (list(spec.get("https_only", {}).items()) if is_ssl else []):
        out[name] = "; ".join(value) if isinstance(value, list) else str(value)
    return out


def _quote(value):
    """An Apache argument in double quotes."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def block():
    """The <IfModule mod_headers.c> block for a static folder's .htaccess."""
    https_only = set(_spec().get("https_only", {}))
    lines = ["<IfModule mod_headers.c>"]
    for name, value in headers(True).items():
        # %{HTTPS} rather than env=HTTPS: mod_ssl only sets that variable after the /people/ 301 is made
        lines.append(f"Header always set {name} {_quote(value)}" + (" \"expr=%{HTTPS} == 'on'\"" if name in https_only else ""))
    lines.append("</IfModule>")
    return "\n".join(lines) + "\n"


def htaccess(folder, extra=""):
    """A whole .htaccess for a static folder: the header block, then any rules of its own."""
    head = (f"# /{folder}/ is served by Apache as files, so WordPress never sends its security headers here:\n"
            "# the same ones (wp/inc/security-headers.json, card #6449). Generated by\n"
            "# design/new-hero-2026-10/static_headers.py; uploaded by deploy-wp-theme-vimexx.py.\n")
    return head + block() + (("\n" + extra) if extra else "")


if __name__ == "__main__":
    print(htaccess("example"), end="")
