#!/usr/bin/env python3
"""
Port the static design in THIS folder into the real `prospergenics-theme`
WordPress theme (repo root), as opposed to build-wp-theme.py which generates the
standalone, self-contained `prospergenics-2026` theme.

    python port-to-theme.py

Why this exists: the standalone generated theme carries no wp_head() SEO layer,
so promoting it to production would drop every schema/meta improvement that
lives in the real theme's functions.php (Organization + Person JSON-LD, front
page + /trainings/ + NL meta descriptions, og/twitter tags, speakable, hreflang,
security headers, legacy redirects). Porting into the real theme keeps all of it.

Writes (all overwritten on every run — edit the design source, not these):
  ../../css/hero-2026.css   <- the <style> block, asset url() rehomed to ../assets/
  ../../js/hero-2026.js     <- the inline <script>, asset paths via PG_HERO.assets
  ../../front-page.php      <- the <body> markup, wrapped in get_header/get_footer('2026')
  ../../assets/             <- assets/

Left alone because they are hand-maintained, not generated:
  header-2026.php, footer-2026.php, functions.php (enqueue block),
  template-parts/team-story-2026.php
"""
import os, re, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
THEME = os.path.normpath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(HERE, "index.html")

TPL = "<?php echo esc_url( get_template_directory_uri() ); ?>"

GENERATED = "GENERATED by design/new-hero-2026-10/port-to-theme.py -- edit the design source, not this file."


def read_lines():
    with open(SRC, encoding="utf-8") as f:
        return f.read().split("\n")


def span(lines, open_pat, close_pat):
    """1-based inclusive content range between the lines matching the two patterns."""
    start = end = None
    for i, ln in enumerate(lines, 1):
        if start is None and re.match(open_pat, ln):
            start = i + 1
        elif start is not None and end is None and re.match(close_pat, ln):
            end = i - 1
            break
    if start is None or end is None:
        raise SystemExit(f"could not locate {open_pat!r}..{close_pat!r} in index.html")
    return "\n".join(lines[start - 1:end])


def write(rel, body):
    path = os.path.join(THEME, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(body)
    print(f"  wrote {rel} ({len(body.splitlines())} lines)")


def build():
    lines = read_lines()

    # ---------------------------------------------------------------- CSS
    css = span(lines, r"^<style>", r"^</style>")
    # the stylesheet now lives one directory deep, so assets/ is ../assets/
    css = css.replace("url('assets/", "url('../assets/").replace('url("assets/', 'url("../assets/')
    write("css/hero-2026.css", f"/* {GENERATED} */\n{css}\n")

    # ---------------------------------------------------------------- JS
    js = span(lines, r"^  <script>$", r"^  </script>$")
    # image paths in the SLIDES array must resolve against the theme directory
    js = js.replace('img:"assets/', 'img:PG_ASSETS+"')
    preamble = (
        f"/* {GENERATED} */\n"
        "// PG_HERO is injected by wp_localize_script() in functions.php; the fallback keeps\n"
        "// this file working when opened straight from the design folder.\n"
        "const PG_ASSETS = ( window.PG_HERO && window.PG_HERO.assets ) || 'assets/';\n"
    )
    write("js/hero-2026.js", preamble + js + "\n")

    # ---------------------------------------------------------------- markup
    markup = span(lines, r"^<body>", r"^  <script>$")
    # drop the trailing third-party embed <script> + blank lines; it is re-emitted
    # from the template below so its required data-* attributes stay intact
    markup = re.sub(r"\n\s*<!-- ProsperGenics coach chat.*?</script>\s*$", "", markup, flags=re.S)
    markup = markup.replace('src="assets/', f'src="{TPL}/assets/')
    markup = markup.replace('href="assets/', f'href="{TPL}/assets/')
    # inline style="background-image:url('assets/...')" on the project/service cards
    markup = markup.replace("url('assets/", f"url('{TPL}/assets/")
    markup = markup.replace('url(&quot;assets/', f'url(&quot;{TPL}/assets/')
    markup = markup.replace("url(assets/", f"url({TPL}/assets/")
    # the design's own team-quote flow stays as designed; the approved Team Story
    # quotes (functions.php getter, live-verified) render from a template part
    markup = markup.replace(
        "  <!-- VALUE TEST",
        "  <?php get_template_part( 'template-parts/team-story-2026' ); ?>\n\n  <!-- VALUE TEST",
        1,
    )

    front = f"""<?php
/**
 * Front page -- ProsperGenics 2026 design.
 *
 * {GENERATED}
 *
 * Uses the stripped header-2026/footer-2026 parts: the design is a self-contained
 * landing page with no site nav or site footer of its own, but it still needs
 * wp_head()/wp_footer() so the theme's SEO layer (JSON-LD, meta descriptions,
 * og/twitter tags, hreflang) keeps printing. CSS/JS are enqueued from
 * functions.php (prospergenics_hero_2026_assets), not inlined.
 */

get_header( '2026' );
?>
<main id="main-content">
{markup}
</main>

<?php
/*
 * Third-party CoachOS chat embed: kept as a literal tag rather than enqueued because
 * its data-* attributes (tenant/lang/title/color/trigger/position) are part of its API
 * and the launcher orb above is its declared trigger.
 */
?>
<script src="https://coaching.martiendejong.nl/coaching/embed.js?v=2" data-tenant="prospergenics"
        data-lang="en" data-title="Chat with ProsperGenics" data-color="#1a7a46"
        data-trigger=".launcher-orb" data-position="right" async></script>
<?php

get_footer( '2026' );
"""
    write("front-page.php", front)

    # ---------------------------------------------------------------- assets
    dst = os.path.join(THEME, "assets")
    if os.path.isdir(dst):
        shutil.rmtree(dst)
    shutil.copytree(os.path.join(HERE, "assets"), dst)
    print(f"  wrote assets/ ({len(os.listdir(dst))} files)")


if __name__ == "__main__":
    print(f"porting design -> {THEME}")
    build()
    print("done. Re-run after every design change.")
